-- (checked by apps/core-api/test/spotify-migration.test.ts). Additive, re-runnable.
-- « Choisi la prochaine musique ! » without SAMMI: Core holds the requests (one row per redemption action: the Twitch
-- redemption id is the dedup key), their life (received → in Spotify's queue → playing → played / skipped / canceled /
-- removed / refused / unknown) and the logical queue; Studio (the only Spotify caller) runs the jobs and reports what
-- Spotify plays; the bot changes the redemption's status on Twitch (cp_twitch_actions, once per redemption).

create table if not exists spotify_settings (
  channel_id text primary key,
  enabled boolean not null default false,
  max_pending_per_viewer integer not null default 2 check (max_pending_per_viewer between 1 and 10),
  viewer_cooldown_seconds integer not null default 600 check (viewer_cooldown_seconds between 0 and 3600),
  max_duration_seconds integer not null default 600 check (max_duration_seconds between 60 and 1800),
  cancel_grace_seconds integer not null default 10 check (cancel_grace_seconds between 0 and 60),
  updated_at timestamptz not null,
  updated_by text
);

-- Studio's last sync (its Spotify status) and last playback reading: one row per channel.
create table if not exists spotify_studio (
  channel_id text primary key,
  seen_at timestamptz not null,
  status jsonb not null,
  playback jsonb,
  playback_at timestamptz,
  -- The request the current track is attributed to (Core's decision), or null.
  current_request_id uuid
);

create table if not exists spotify_requests (
  request_id uuid primary key,
  -- Arrival order (ties of the same instant): the logical queue is FIFO.
  seq bigint generated by default as identity,
  channel_id text not null,
  source text not null check (source in ('twitch', 'simulation')),
  -- '<source>:<redemption id>:<action index>': a redelivered redemption finds its request (never a second one).
  source_ref text not null,
  reward_id text,
  redemption_id text,
  viewer_id text not null,
  viewer_login text not null,
  viewer_name text not null,
  raw_input text not null,
  mode text check (mode in ('search', 'exact')),
  state text not null check (state in ('RECEIVED', 'SEARCHING', 'QUEUED', 'PLAYING', 'PLAYED', 'SKIPPED', 'CANCELED',
    'REMOVED_BY_MOD', 'FAILED', 'AMBIGUOUS', 'TOO_LONG', 'VIEWER_LIMIT', 'VIEWER_COOLDOWN', 'UNKNOWN')),
  reason text,
  track jsonb,
  candidates jsonb,
  confidence text,
  margin numeric,
  max_duration_ms integer not null,
  confirmation text check (confirmation in ('http_204', 'queue_readback')),
  received_at timestamptz not null,
  -- In Spotify's queue (or may be: an uncertain addition proven by a queue read).
  queued_at timestamptz,
  playback_started_at timestamptz,
  ended_at timestamptz,
  end_reason text,
  canceled_at timestamptz,
  canceled_by text,
  removed_at timestamptz,
  removed_by text,
  skipped_by text,
  -- Canceled / removed while in Spotify's queue: skipped as soon as Spotify plays it, once (consumed_at).
  auto_skip boolean not null default false,
  auto_skip_consumed_at timestamptz,
  auto_skip_result text,
  -- The redemption on Twitch: null (nothing asked yet), cancel_requested (points given back), fulfill_requested,
  -- unmanaged (the reward is not Raptoru's: Twitch lets only its creator change it), none (simulation).
  twitch_status text check (twitch_status in ('cancel_requested', 'kept', 'unmanaged', 'none')),
  updated_at timestamptz not null,
  unique (channel_id, source_ref)
);
create index if not exists spotify_requests_state_idx on spotify_requests (channel_id, state);
create index if not exists spotify_requests_viewer_idx on spotify_requests (channel_id, viewer_id, state);
create index if not exists spotify_requests_received_idx on spotify_requests (channel_id, received_at desc);

-- Jobs for Studio (the only one that calls Spotify): a song request to search and queue, a skip, a playback read. A job
-- claimed (attempt) is never handed out again: an unreported one expires (it may have run).
create table if not exists spotify_jobs (
  job_id uuid primary key,
  channel_id text not null,
  kind text not null check (kind in ('song_request', 'skip', 'read_playback')),
  request_id uuid,
  payload jsonb not null,
  status text not null check (status in ('queued', 'running', 'done', 'expired')),
  attempt_id uuid,
  lease_expires_at timestamptz,
  result jsonb,
  -- What to answer in the chat when it ends (the `!song` / `!songskip` author), or null.
  reply jsonb,
  created_at timestamptz not null,
  updated_at timestamptz not null
);
create index if not exists spotify_jobs_status_idx on spotify_jobs (channel_id, status);

-- Twitch-side channel points actions, decided by Core, run once by the bot: a redemption's status (FULFILLED / CANCELED
-- = refund), the creation of a reward owned by Raptoru's app. The key makes each one unique (one status per redemption).
create table if not exists cp_twitch_actions (
  action_id uuid primary key,
  channel_id text not null,
  kind text not null check (kind in ('redemption_status', 'reward_create')),
  idempotency_key text not null unique,
  payload jsonb not null,
  status text not null check (status in ('queued', 'running', 'done', 'failed', 'unknown')),
  attempt_id uuid,
  attempts integer not null default 0,
  lease_expires_at timestamptz,
  http_status integer,
  error text,
  result jsonb,
  created_at timestamptz not null,
  updated_at timestamptz not null
);
create index if not exists cp_twitch_actions_status_idx on cp_twitch_actions (channel_id, status);

-- A reward created by Raptoru's app (only those can be fulfilled / refunded by Raptoru).
alter table cp_rewards add column if not exists managed_by_raptoru boolean not null default false;
