import type { Core } from '../app.js';
import { alertsRoutes } from '../http/alerts-routes.js';
import { cautionRoutes } from '../http/caution-routes.js';
import { challengesRoutes } from '../http/challenges-routes.js';
import { channelPointsRoutes } from '../http/channel-points-routes.js';
import { dockRoutes } from '../http/dock-routes.js';
import { progressionRoutes } from '../http/progression-routes.js';
import { randomBanRoutes } from '../http/random-ban-routes.js';
import type { Route } from '../http/server.js';
import { spotifyRoutes } from '../http/spotify-routes.js';
import { votekickRoutes } from '../http/votekick-routes.js';

// The rest of the Lab route table, ONLY in the Lab environment of the main Core (CORE_ENVIRONMENT=lab): the routes
// Studio's Lab screens and simulators use (alert tests, Spotify and Roue du Sub simulators, Random Ban and Caution tests…),
// generated by the same functions as Production's /v1/studio/* ones, on the same services. They stay in-process behind
// the cockpit (a paired Studio's credential): never mounted on the HTTP server, never on a Production Core.

export function labCockpitRoutes(core: Core, channelId: string): Route[] {
  const site = { channelId, production: false, site: true };
  return [
    ...alertsRoutes(core.alerts, undefined, core.subWheel),
    ...channelPointsRoutes(core.channelPoints),
    ...randomBanRoutes(core.randomBan),
    ...dockRoutes(core.dock),
    ...progressionRoutes(core.progression, site),
    ...challengesRoutes(core.challenges, site),
    ...cautionRoutes(core.caution),
    ...votekickRoutes(core.votekick),
    ...spotifyRoutes(core.spotify, core.cpTwitch),
  ];
}
