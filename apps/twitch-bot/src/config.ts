const Flag = z.enum(['true', 'false']).default('false');

/** Consent is independent from execution switches. These are the approved durable profiles. */
export function authorizationScopes(role: TwitchOAuthRole): string[] {
  return [...TWITCH_OAUTH_PROFILES[role].scopes];
}

export function twitchTokenPathsConflict(config: {
  TWITCH_TOKEN_FILE: string;
  TWITCH_BROADCASTER_TOKEN_FILE: string;
}): boolean {
  const normalize = (path: string) => {
    const absolute = resolve(path);
    return process.platform === 'win32' ? absolute.toLowerCase() : absolute;
  };
  return (
    normalize(config.TWITCH_TOKEN_FILE) ===
    normalize(config.TWITCH_BROADCASTER_TOKEN_FILE)
  );
}

function distinctTokenPaths<
  T extends {
    TWITCH_TOKEN_FILE: string;
    TWITCH_BROADCASTER_TOKEN_FILE: string;
  },
>(config: T): T {
  if (twitchTokenPathsConflict(config))
    throw new Error(
      'Les fichiers des autorisations bot et broadcaster doivent être distincts.',
    );
  return config;
}

