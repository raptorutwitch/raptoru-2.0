import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { TWITCH_OAUTH_PROFILES, type TwitchOAuthRole } from '@raptoru/schemas';
import { z } from 'zod';

const Flag = z.enum(['true', 'false']).default('false');

/** Consent is independent from execution switches. These are the approved durable profiles. */
export function authorizationScopes(role: TwitchOAuthRole): string[] {
  return [...TWITCH_OAUTH_PROFILES[role].scopes];
}

export function twitchTokenPathsConflict(config: {
  TWITCH_TOKEN_FILE: string;
  TWITCH_BROADCASTER_TOKEN_FILE: string;
}): boolean {
  const normalize = (path: string) => {
    const absolute = resolve(path);
    return process.platform === 'win32' ? absolute.toLowerCase() : absolute;
  };
  return (
    normalize(config.TWITCH_TOKEN_FILE) ===
    normalize(config.TWITCH_BROADCASTER_TOKEN_FILE)
  );
}

function distinctTokenPaths<
  T extends {
    TWITCH_TOKEN_FILE: string;
    TWITCH_BROADCASTER_TOKEN_FILE: string;
  },
>(config: T): T {
  if (twitchTokenPathsConflict(config))
    throw new Error(
      'Les fichiers des autorisations bot et broadcaster doivent être distincts.',
    );
  return config;
}

/** Generated by `npm run twitch:auth`, git-ignored. Same path from src/ (tsx) and dist/ (node). */
export const DEFAULT_BROADCASTER_TOKEN_FILE = fileURLToPath(
  new URL('../.twitch-tokens.broadcaster.json', import.meta.url),
);

/**
 * Scopes of the broadcaster token (`npm run twitch:auth -- --broadcaster`, logged in as the
 * broadcaster): subscriptions (tier resolution and sub/gift events), cheers, follows.
 */
export const BROADCASTER_SCOPES = [
  'channel:read:subscriptions',
  'bits:read',
  'moderator:read:followers',
];

/**
 * Runtime capabilities needed on the broadcaster token: loyalty's, plus redemption reads when Points de chaîne is on.
 * (CHANNEL_POINTS_EVENTS). Read only: Raptoru never manages a redemption. Random Ban V2 (RANDOM_BAN): moderation:read
 * (the moderators and the bans / timeouts of the chatters, read only) and channel:read:subscriptions (3 or 5 min).
 */
export function broadcasterScopes(
  config: Partial<
    Pick<
      TwitchAppConfig,
      'LOYALTY_TWITCH_EVENTS' | 'CHANNEL_POINTS_EVENTS' | 'RANDOM_BAN'
    >
  >,
): string[] {
  const loyalty = config.LOYALTY_TWITCH_EVENTS !== 'false';
  return [
    ...new Set([
      ...(loyalty ? BROADCASTER_SCOPES : []),
      ...(config.CHANNEL_POINTS_EVENTS === 'true'
        ? ['channel:read:redemptions']
        : []),
      ...(config.RANDOM_BAN === 'true'
        ? ['moderation:read', 'channel:read:subscriptions']
        : []),
    ]),
  ];
}

