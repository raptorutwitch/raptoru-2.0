export type TwitchAppConfig = z.infer<typeof TwitchApp>;
export type BotConfig = z.infer<typeof Env>;

function parse<T>(
  schema: z.ZodType<T>,
  env: NodeJS.ProcessEnv,
  what: string,
): T {
  const result = schema.safeParse(env);
  if (!result.success) {
    const fields = result.error.issues.map((i) => i.path.join('.')).join(', ');
    throw new Error(`invalid ${what} environment: ${fields}`);
  }
  return result.data;
}

const LOCAL_HOSTS = new Set(['localhost', '127.0.0.1', '[::1]']);

export function loadConfig(env: NodeJS.ProcessEnv = process.env): BotConfig {
  const config = distinctTokenPaths(parse(Env, env, 'twitch-bot'));
  if (
    config.BOT_LEASE_OPTIONAL === 'true' &&
    !LOCAL_HOSTS.has(new URL(config.CORE_API_URL).hostname)
  )
    throw new Error(
      'invalid twitch-bot environment: BOT_LEASE_OPTIONAL is for a local development Core only',
    );
  return config;
}

export function loadTwitchAppConfig(
  env: NodeJS.ProcessEnv = process.env,
): TwitchAppConfig {
  return distinctTokenPaths(parse(TwitchApp, env, 'Twitch app'));
}

/** Runtime capabilities for enabled features. These do not determine consent requests. */
export function requiredScopes(
  config: Pick<
    TwitchAppConfig,
    | 'DAILY_CHAT_COMMANDS'
    | 'LOYALTY_CHAT_COMMANDS'
    | 'PRESENCE_SHADOW'
    | 'LAB_CHAT_INGEST'
  > &
    Partial<
      Pick<
        TwitchAppConfig,
        'LAB_CHAT_OUTPUT' | 'LAB_ALERTS_FOLLOW' | 'RANDOM_BAN'
      >
    >,
): string[] {
  const chatCommands =
    config.DAILY_CHAT_COMMANDS === 'true' ||
    config.LOYALTY_CHAT_COMMANDS === 'true';
  const labOutput = config.LAB_CHAT_OUTPUT === 'true';
  const scopes = [
    ...(chatCommands ? ['user:read:chat', 'user:write:chat'] : []),
    // Reading only: the Lab ingestion never writes to the chat.
    ...(!chatCommands && config.LAB_CHAT_INGEST === 'true'
      ? ['user:read:chat']
      : []),
    ...(config.PRESENCE_SHADOW === 'true' ? ['moderator:read:chatters'] : []),
    ...(labOutput ? ['user:write:chat', 'moderator:manage:announcements'] : []),
    ...(config.LAB_ALERTS_FOLLOW === 'true'
      ? ['moderator:read:followers']
      : []),
    ...(config.RANDOM_BAN === 'true'
      ? [
          'moderator:read:chatters',
          'moderator:read:followers',
          'moderator:manage:banned_users',
        ]
      : []),
  ];
  return [...new Set(scopes)];
}
