// Twitch application of Raptoru 2.0 (Developer Console, confidential client). Shared by the bot,
// `twitch:auth` and the preflight.
const TwitchApp = z.object({
  TWITCH_CLIENT_ID: z.string().min(1),
  TWITCH_CLIENT_SECRET: z.string().min(1),
  TWITCH_BROADCASTER_ID: z.string().regex(/^\d+$/),
  TWITCH_TOKEN_FILE: z.string().min(1).default(DEFAULT_TOKEN_FILE),
  TWITCH_BROADCASTER_TOKEN_FILE: z
    .string()
    .min(1)
    .default(DEFAULT_BROADCASTER_TOKEN_FILE),
  // Answers !daily / !streak in chat. Never 'true' on the production channel before the cutover.
  DAILY_CHAT_COMMANDS: Flag,
  // !solde / !give / !wallet in chat. Never 'true' on the production channel before the cutover.
  LOYALTY_CHAT_COMMANDS: Flag,
  // Forwards subs, gifts, cheers and follows to Core (needs the broadcaster token). Core alone
  // decides shadow / preview / credit; nothing is written to chat.
  LOYALTY_TWITCH_EVENTS: Flag,
  // Points de chaîne V1: the broadcaster connection also receives the channel points redemptions (read only) and
  // reads the reward list; needs channel:read:redemptions on the broadcaster token. Core's master switch (OFF by
  // default) decides whether anything is executed.
  CHANNEL_POINTS_EVENTS: Flag,
  /**
   * Random Ban V2 (docs/RANDOM_BAN_V2.md): runtime capability requirements — LeCroupier_:
   * moderator:manage:banned_users (timeouts) + moderator:read:chatters / moderator:read:followers; broadcaster:
   * moderation:read. OFF by default; consent profiles stay fixed and the Lab executor reports actual grants.
   */
  RANDOM_BAN: Flag,
  // Loyalty events not yet answered by Core (survives bot restarts), git-ignored.
  LOYALTY_OUTBOX_FILE: z.string().min(1).default(DEFAULT_LOYALTY_OUTBOX_FILE),
  // Channel points redemptions not yet answered by Core (survives bot restarts; a redemption may grant credits).
  CHANNEL_POINTS_OUTBOX_FILE: z
    .string()
    .min(1)
    .default(DEFAULT_CHANNEL_POINTS_OUTBOX_FILE),
  // Shadow presence tracker (Get Chatters, read-only). Needs scope moderator:read:chatters.
  PRESENCE_SHADOW: Flag,
  // Lab chat ingestion (Studio « Ingestion chat Twitch » switch: reads the chat for the Lab modules,
  // writes nothing). Requires user:read:chat at runtime; consent remains independent of this flag.
  LAB_CHAT_INGEST: Flag,
  // Commands V2 Lab chat output (LeCroupier_ sends the command answers while Studio's « Sortie chat
  // réelle » is ON — OFF by default in Core). Runtime needs user:write:chat (Send Chat Message)
  // and moderator:manage:announcements (announce mode); the consent profile already contains both.
  LAB_CHAT_OUTPUT: Flag,
  // Twitch alerts, follows (Lab): runtime capability moderator:read:followers (channel.follow v2 read
  // by the moderator LeCroupier_). Receiving them still needs Studio's « Événements Twitch réels » mode.
  LAB_ALERTS_FOLLOW: Flag,
  // Bot journal of the Lab chat sends (about_to_send → outcome), git-ignored runtime data.
  LAB_CHAT_JOURNAL_FILE: z.string().min(1).default('.lab-chat-journal.json'),
  /** Random Ban V2: timeouts about to be sent / sent, until Core knows their outcome (never sent twice). */
  LAB_RANDOM_BAN_JOURNAL_FILE: z
    .string()
    .min(1)
    .default('.lab-random-ban-journal.json'),
});

const Env = TwitchApp.extend({
  CORE_API_URL: z.url(),
  BOT_SECRET: z.string().min(16),
  STREAM_SYNC_INTERVAL_MS: z.coerce.number().int().min(10_000).default(60_000),
});

export type TwitchAppConfig = z.infer<typeof TwitchApp>;
export type BotConfig = z.infer<typeof Env>;

function parse<T>(
  schema: z.ZodType<T>,
  env: NodeJS.ProcessEnv,
  what: string,
): T {
  const result = schema.safeParse(env);
  if (!result.success) {
    const fields = result.error.issues.map((i) => i.path.join('.')).join(', ');
    throw new Error(`invalid ${what} environment: ${fields}`);
  }
  return result.data;
}

export function loadConfig(env: NodeJS.ProcessEnv = process.env): BotConfig {
  return distinctTokenPaths(parse(Env, env, 'twitch-bot'));
}

export function loadTwitchAppConfig(
  env: NodeJS.ProcessEnv = process.env,
): TwitchAppConfig {
  return distinctTokenPaths(parse(TwitchApp, env, 'Twitch app'));
}

/** Runtime capabilities for enabled features. These do not determine consent requests. */
export function requiredScopes(
  config: Pick<
    TwitchAppConfig,
    | 'DAILY_CHAT_COMMANDS'
    | 'LOYALTY_CHAT_COMMANDS'
    | 'PRESENCE_SHADOW'
    | 'LAB_CHAT_INGEST'
  > &
    Partial<
      Pick<
        TwitchAppConfig,
        'LAB_CHAT_OUTPUT' | 'LAB_ALERTS_FOLLOW' | 'RANDOM_BAN'
      >
    >,
): string[] {
  const chatCommands =
    config.DAILY_CHAT_COMMANDS === 'true' ||
    config.LOYALTY_CHAT_COMMANDS === 'true';
  const labOutput = config.LAB_CHAT_OUTPUT === 'true';
  const scopes = [
    ...(chatCommands ? ['user:read:chat', 'user:write:chat'] : []),
    // Reading only: the Lab ingestion never writes to the chat.
    ...(!chatCommands && config.LAB_CHAT_INGEST === 'true'
      ? ['user:read:chat']
      : []),
    ...(config.PRESENCE_SHADOW === 'true' ? ['moderator:read:chatters'] : []),
    ...(labOutput ? ['user:write:chat', 'moderator:manage:announcements'] : []),
    ...(config.LAB_ALERTS_FOLLOW === 'true'
      ? ['moderator:read:followers']
      : []),
    ...(config.RANDOM_BAN === 'true'
      ? [
          'moderator:read:chatters',
          'moderator:read:followers',
          'moderator:manage:banned_users',
        ]
      : []),
  ];
  return [...new Set(scopes)];
}
